"""Terminal + markdown reporting for an EvalSummary. Everything printed is computed from the run."""
import json
import sys
import time
from typing import Any, Dict, List

from rich.console import Console
from rich.panel import Panel
from rich.table import Table

from config.settings import settings
from eval.harness import EvalSummary, summary_to_dict
from eval.metrics import FIELDS_TO_EVALUATE, __doc__ as MATCHING_RULES

SHORT = {"is_invoice": "Inv", "vendor": "Vend", "invoice_number": "Num", "invoice_date": "Date",
         "currency": "Curr", "line_items": "Items", "tax_total": "Tax", "total": "Tot"}


def _console() -> Console:
    # Windows cp1252 consoles cannot print ✓/✗; force UTF-8 where possible, else fall back to ASCII marks.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    except Exception:
        pass
    return Console(legacy_windows=False, soft_wrap=False)


def _marks(console: Console):
    enc = (getattr(sys.stdout, "encoding", "") or "").lower()
    return ("✓", "✗") if "utf" in enc else ("OK", "X")


def _short(v: Any, n: int = 70) -> str:
    s = json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else v
    return s if len(s) <= n else s[: n - 1] + "…"


def print_eval_report(summary: EvalSummary, save: bool = True) -> str:
    console = _console()
    ok, bad = _marks(console)

    t = Table(title=f"Field accuracy - labelled set ({summary.total_docs} docs)\nBackend: {summary.mode}",
              header_style="bold cyan", show_lines=False)
    for col, j in (("Field", "left"), ("Correct", "center"), ("Accuracy", "right")):
        t.add_column(col, justify=j)
    for f in FIELDS_TO_EVALUATE:
        acc = summary.field_accuracy[f]
        color = "green" if acc >= 90 else "yellow" if acc >= 70 else "red"
        t.add_row(f, f"{summary.field_correct_counts[f]}/{summary.total_docs}", f"[{color}]{acc:.1f}%[/{color}]")
    t.add_row("[bold]OVERALL[/bold]", f"{sum(summary.field_correct_counts.values())}/{summary.total_docs * 8}",
              f"[bold]{summary.overall_accuracy:.1f}%[/bold]")
    console.print(t)

    d = Table(title="Per-document matrix", header_style="bold magenta")
    d.add_column("Doc")
    for f in FIELDS_TO_EVALUATE:
        d.add_column(SHORT[f], justify="center")
    d.add_column("Review", justify="center")
    d.add_column("Calls", justify="right")
    d.add_column("Sec", justify="right")
    for r in summary.document_records:
        row = [r.doc_id] + [f"[green]{ok}[/green]" if r.field_matches[f] else f"[red]{bad}[/red]" for f in FIELDS_TO_EVALUATE]
        row += ["[yellow]flag[/yellow]" if r.needs_review else "-", str(r.calls), f"{r.elapsed_s:.1f}"]
        d.add_row(*row)
    console.print(d)

    if summary.error_groups:
        g = Table(title="Errors grouped by cause", header_style="bold red")
        g.add_column("Field: cause")
        g.add_column("Docs")
        for k, docs in summary.error_groups.items():
            g.add_row(k, ", ".join(docs))
        console.print(g)

    rv = summary.review
    console.print(Panel(
        f"Docs fully correct: {summary.docs_fully_correct}/{summary.total_docs}   |   "
        f"Line-item rows: precision {summary.line_item_row_precision:.1%}, recall {summary.line_item_row_recall:.1%}\n"
        f"needs_review flagged {rv['flagged_docs']} docs; docs with >=1 error: {rv['docs_with_errors']}; "
        f"flag precision {rv['precision']}, recall {rv['recall']}; "
        f"errors inside flagged docs: {rv['error_fields_in_flagged_docs']}/{rv['error_fields_total']}\n"
        f"Tokens in {summary.total_tokens_in:,} | out {summary.total_tokens_out:,} | "
        f"list-price cost ${summary.total_cost_usd:.5f} total, ${summary.avg_cost_per_doc:.5f}/doc | "
        f"wall time {summary.wall_time_s}s",
        title="Summary", border_style="green"))

    md = generate_markdown_report(summary)
    if save:
        save_reports(md, summary)
        console.print(f"Reports written to {settings.resolve_path('reports')}")
    else:
        console.print("--no-save: outputs/ and reports/ left untouched")
    return md


def generate_markdown_report(s: EvalSummary) -> str:
    L: List[str] = [
        "# Evaluation report (generated by `python scripts/eval.py`)", "",
        f"- Generated: {time.strftime('%Y-%m-%d %H:%M')}",
        f"- Backend: `{s.mode}`",
        f"- Documents: {s.total_docs} labelled (L01-L10)",
        f"- Overall field accuracy: **{s.overall_accuracy:.1f}%** ({sum(s.field_correct_counts.values())}/{s.total_docs * 8})",
        f"- Documents with every field correct: **{s.docs_fully_correct}/{s.total_docs}**",
        f"- Line-item rows: precision {s.line_item_row_precision:.1%}, recall {s.line_item_row_recall:.1%}",
        f"- Wall time: {s.wall_time_s}s", "",
        "## Field-level accuracy", "",
        "| Field | Correct | Accuracy |", "|---|---|---|",
    ]
    for f in FIELDS_TO_EVALUATE:
        L.append(f"| `{f}` | {s.field_correct_counts[f]}/{s.total_docs} | {s.field_accuracy[f]:.1f}% |")
    L.append(f"| **overall** | {sum(s.field_correct_counts.values())}/{s.total_docs * 8} | **{s.overall_accuracy:.1f}%** |")

    L += ["", "## Per-document matrix", "",
          "| Doc | " + " | ".join(SHORT[f] for f in FIELDS_TO_EVALUATE) + " | needs_review | calls | tokens in/out | sec |",
          "|---" * (len(FIELDS_TO_EVALUATE) + 5) + "|"]
    for r in s.document_records:
        cells = ["✅" if r.field_matches[f] else "❌" for f in FIELDS_TO_EVALUATE]
        L.append(f"| {r.doc_id} | " + " | ".join(cells) +
                 f" | {'flagged' if r.needs_review else '-'} | {r.calls} | {r.tokens_in}/{r.tokens_out} | {r.elapsed_s:.1f} |")

    L += ["", "## Errors grouped by cause", ""]
    if not s.error_groups:
        L.append("No field errors on the labelled set.")
    else:
        L += ["| Field: cause | Count | Docs |", "|---|---|---|"]
        for k, docs in s.error_groups.items():
            L.append(f"| {k} | {len(docs)} | {', '.join(docs)} |")
        L += ["", "### Examples", ""]
        for r in s.document_records:
            for f, tag in r.errors.items():
                pred = (r.predicted or {}).get(f)
                gt = r.ground_truth.get(f)
                if f == "line_items":
                    L.append(f"- **{r.doc_id} / {f}** ({tag}): rows pred {r.line_items.get('pred_rows')} vs gt "
                             f"{r.line_items.get('gt_rows')}, problems {r.line_items.get('problems')}")
                else:
                    L.append(f"- **{r.doc_id} / {f}** ({tag}): predicted `{_short(pred)}`, expected `{_short(gt)}`")
                if r.issues:
                    L.append(f"  - validator said: {_short('; '.join(r.issues), 200)}")

    rv = s.review
    L += ["", "## Does `needs_review` catch the errors?", "",
          "A document is *flagged* when validation errors/warnings survive the corrective retries.", "",
          "| | has errors | no errors |", "|---|---|---|",
          f"| flagged | {rv['true_positive']} | {rv['false_positive']} |",
          f"| not flagged | {rv['false_negative']} | {rv['true_negative']} |", "",
          f"- Flag precision: {rv['precision']}  -  flag recall: {rv['recall']}",
          f"- Field errors inside flagged documents: {rv['error_fields_in_flagged_docs']} of {rv['error_fields_total']}"
          + (f" ({rv['share_of_errors_caught']:.0%})" if rv["share_of_errors_caught"] is not None else ""), ""]

    L += ["## Cost", "",
          f"- Tokens: {s.total_tokens_in:,} in, {s.total_tokens_out:,} out "
          f"(avg {s.total_tokens_in // max(1, s.total_docs):,} in / {s.total_tokens_out // max(1, s.total_docs):,} out per doc, "
          "including corrective retries).",
          f"- Cost at list price: **${s.total_cost_usd:.5f}** total, **${s.avg_cost_per_doc:.5f} per document**.",
          "- Method: for every API call, `prompt_tokens * input_price + completion_tokens * output_price`, using the "
          "token counts returned by the API and the per-token prices below; summed per document. Groq's free tier "
          "actually billed $0, the list price is what a paid account would pay.", ""]
    if s.pricing:
        L += ["| Model | USD / 1M input | USD / 1M output | Price source |", "|---|---|---|---|"]
        for m, p in s.pricing.items():
            if p:
                L.append(f"| `{m}` | {p['input_per_1k'] * 1000:.3f} | {p['output_per_1k'] * 1000:.3f} | {p.get('source', '')} |")

    L += ["", "## Matching rules", "", "```", (MATCHING_RULES or "").strip(), "```"]
    return "\n".join(L)


def save_reports(markdown_content: str, summary: EvalSummary):
    rep_dir = settings.resolve_path("reports")
    rep_dir.mkdir(parents=True, exist_ok=True)
    (rep_dir / "accuracy_table.md").write_text(markdown_content, encoding="utf-8")
    (rep_dir / "eval_results.json").write_text(
        json.dumps(summary_to_dict(summary), indent=2, ensure_ascii=False, default=str), encoding="utf-8")
